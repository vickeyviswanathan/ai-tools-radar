// Generates reports/TOOL_REVIEW_CLAIMS.md: for ten representative tool-review pages, lists exactly which statements on
// the page are derived by rule (URL host / category) rather than verified against the tool's own documentation.
// It flags them; it does not rewrite or invent replacements.
// Usage: node scripts/report-tool-claims.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { deriveToolEvaluation } from "../src/programmatic-seo.mjs";

const SELECTED = ["ollama", "llama-cpp", "vllm", "dify", "open-webui", "comfyui", "claude-code", "lm-studio", "n8n", "ragflow"];
const tools = JSON.parse(readFileSync("public/data/tools.json", "utf8")).tools;
const bySlug = new Map(tools.map((t) => [t.slug, t]));

const rows = [];
for (const slug of SELECTED) {
  const t = bySlug.get(slug);
  if (!t) { rows.push(`| \`${slug}\` | (not in current index) | | | |`); continue; }
  const e = deriveToolEvaluation(t);
  const type = e.isGithub ? "SoftwareSourceCode" : "SoftwareApplication";
  const hostBasis = e.isGithub ? "URL is on github.com" : e.isHf ? "URL is on huggingface.co" : "URL is a product/docs site";
  rows.push(
    `| [\`${slug}\`](https://cipherati.com/tools/${slug}.html) | ${t.category} | \`${type}\` (${hostBasis}) | ${e.isSelfHost ? "Self-hostable shown" : "Managed/cloud shown"} | ${e.isGithub ? "“Open-Source Repository” shown" : "“Commercial / Freemium” shown"} |`
  );
}

const md = `# Tool-review claims that are rule-derived, not source-verified

Generated by \`scripts/report-tool-claims.mjs\` from the current index. These are **flags for review**, not corrections. No replacement
claims were invented.

## What the review template states, and on what basis
| Statement on every review | Basis in code (\`deriveToolEvaluation\`) | Verified against the tool's own docs? |
|---|---|---|
| Deployment & runtime ("Self-Hostable / Local Runtime…") | Any \`github.com\` or \`huggingface.co\` URL, or a name/URL regex list | **No** — a GitHub link does not prove the project can be self-hosted |
| License & access model ("Open-Source Repository…") | Any \`github.com\` URL | **No** — the actual licence is not read; the page only tells readers to inspect LICENSE |
| Data & privacy posture ("zero external telemetry when configured…") | Same self-host inference | **No** — no telemetry audit performed |
| Primary engineering fit / operational caveats | One generic paragraph per category | **No** — category-level, not tool-specific |
| FAQ answers | Templated from the fields above | **No** — inherits the same basis |
| Popularity signal | Stars / likes / HN points from the index | Yes (public metric), and pages state it is not a security audit |

## Ten reviews improved in this change
Improvements applied to **all** review pages by the generator, shown here for ten representative ones:
- Visible breadcrumb now ends in the real category (\`/ai-tools.html#tools/<category>\`) and the JSON-LD BreadcrumbList matches it (4 levels, previously 3).
- Removed an invalid \`programmingLanguage: "AI / Developer Tooling"\` value from SoftwareSourceCode markup.
- \`dateModified\` now comes from the content ledger instead of the build date.
- Previous/next-in-category links added; each review is linked from its category hub card and from related reviews.

| Review | Category | Schema type chosen | Deployment claim | Licence claim |
|---|---|---|---|---|
${rows.join("\n")}

## Recommended follow-up (needs a human with the docs open)
1. For each of the ten above, confirm the actual licence, self-hosting support and telemetry behaviour from the project's own documentation and add them as sourced facts.
2. Until then, consider softening the template wording from "is self-hostable" to "can usually be self-hosted; verify in the project documentation".
3. Do not add benchmark or performance claims without running and logging the tests.
`;
writeFileSync("reports/TOOL_REVIEW_CLAIMS.md", md, "utf8");
console.log("wrote reports/TOOL_REVIEW_CLAIMS.md");
